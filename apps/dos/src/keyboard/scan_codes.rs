use relocade_app::winit::keyboard::KeyCode;

// PC set-1 positions, used by the existing BIOS translated-key interface.
// Extended keys use BIOS scan codes, not raw E0-prefixed controller bytes.
pub(super) fn scan_code(key: KeyCode) -> u8 {
    use KeyCode::*;
    match key {
        Escape => 0x01,
        Digit1 => 0x02,
        Digit2 => 0x03,
        Digit3 => 0x04,
        Digit4 => 0x05,
        Digit5 => 0x06,
        Digit6 => 0x07,
        Digit7 => 0x08,
        Digit8 => 0x09,
        Digit9 => 0x0a,
        Digit0 => 0x0b,
        Minus => 0x0c,
        Equal => 0x0d,
        Backspace => 0x0e,
        Tab => 0x0f,
        KeyQ => 0x10,
        KeyW => 0x11,
        KeyE => 0x12,
        KeyR => 0x13,
        KeyT => 0x14,
        KeyY => 0x15,
        KeyU => 0x16,
        KeyI => 0x17,
        KeyO => 0x18,
        KeyP => 0x19,
        BracketLeft => 0x1a,
        BracketRight => 0x1b,
        Enter | NumpadEnter => 0x1c,
        KeyA => 0x1e,
        KeyS => 0x1f,
        KeyD => 0x20,
        KeyF => 0x21,
        KeyG => 0x22,
        KeyH => 0x23,
        KeyJ => 0x24,
        KeyK => 0x25,
        KeyL => 0x26,
        Semicolon => 0x27,
        Quote => 0x28,
        Backquote => 0x29,
        Backslash => 0x2b,
        KeyZ => 0x2c,
        KeyX => 0x2d,
        KeyC => 0x2e,
        KeyV => 0x2f,
        KeyB => 0x30,
        KeyN => 0x31,
        KeyM => 0x32,
        Comma => 0x33,
        Period => 0x34,
        Slash | NumpadDivide => 0x35,
        NumpadMultiply => 0x37,
        Space => 0x39,
        F1 => 0x3b,
        F2 => 0x3c,
        F3 => 0x3d,
        F4 => 0x3e,
        F5 => 0x3f,
        F6 => 0x40,
        F7 => 0x41,
        F8 => 0x42,
        F9 => 0x43,
        F10 => 0x44,
        Home | Numpad7 => 0x47,
        ArrowUp | Numpad8 => 0x48,
        PageUp | Numpad9 => 0x49,
        NumpadSubtract => 0x4a,
        ArrowLeft | Numpad4 => 0x4b,
        Numpad5 => 0x4c,
        ArrowRight | Numpad6 => 0x4d,
        NumpadAdd => 0x4e,
        End | Numpad1 => 0x4f,
        ArrowDown | Numpad2 => 0x50,
        PageDown | Numpad3 => 0x51,
        Insert | Numpad0 => 0x52,
        Delete | NumpadDecimal => 0x53,
        F11 => 0x85,
        F12 => 0x86,
        _ => 0,
    }
}
