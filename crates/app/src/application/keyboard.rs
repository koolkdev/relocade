use relocade_peripherals::keyboard::{KeyCode, KeyboardEvent, Modifiers};
use winit::{
    event::{ElementState, WindowEvent},
    keyboard::{KeyCode as WinitKey, PhysicalKey},
};

pub(super) fn translate(event: &WindowEvent) -> Option<KeyboardEvent> {
    Some(match event {
        WindowEvent::KeyboardInput {
            event,
            is_synthetic: false,
            ..
        } => KeyboardEvent::Key {
            code: key_code(event.physical_key)?,
            text: event.text.as_ref().map(ToString::to_string),
            pressed: event.state == ElementState::Pressed,
            repeat: event.repeat,
        },
        WindowEvent::ModifiersChanged(modifiers) => {
            let state = modifiers.state();
            KeyboardEvent::Modifiers(Modifiers {
                shift: state.shift_key(),
                control: state.control_key(),
                alt: state.alt_key(),
                super_key: state.super_key(),
            })
        }
        WindowEvent::Focused(false) => KeyboardEvent::FocusLost,
        _ => return None,
    })
}

