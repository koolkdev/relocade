use relocade_peripherals::keyboard::KeyCode;

pub(super) fn control_character(code: KeyCode, text: Option<&str>) -> Option<u8> {
    if let Some(text) = text {
        let mut characters = text.chars();
        let character = characters.next()?;
        if characters.next().is_some() {
            return None;
        }
        return match character {
            '\0'..='\x1f' => Some(character as u8),
            '@'..='_' | 'a'..='z' => Some(character.to_ascii_uppercase() as u8 & 0x1f),
            ' ' => Some(0),
            _ => None,
        };
    }
    use KeyCode::*;
    Some(match code {
        KeyA => 1,
        KeyB => 2,
        KeyC => 3,
        KeyD => 4,
        KeyE => 5,
        KeyF => 6,
        KeyG => 7,
        KeyH => 8,
        KeyI => 9,
        KeyJ => 10,
        KeyK => 11,
        KeyL => 12,
        KeyM => 13,
        KeyN => 14,
        KeyO => 15,
        KeyP => 16,
        KeyQ => 17,
        KeyR => 18,
        KeyS => 19,
        KeyT => 20,
        KeyU => 21,
        KeyV => 22,
        KeyW => 23,
        KeyX => 24,
        KeyY => 25,
        KeyZ => 26,
        BracketLeft => 27,
        Backslash => 28,
        BracketRight => 29,
        _ => return None,
    })
}

